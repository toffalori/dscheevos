#!/usr/bin/env python3
"""Build a small dsd_font_t from a BDF font (the X11 misc-fixed 5x7, public domain).

Glyph table as the display library's 8x8 font: 256 glyphs, one byte per row,
bit 0 = left pixel, eight rows each (rows past the font's height stay 0).
Glyphs are moved to the left edge, so an advance of "rightmost lit column + 1"
(popup.c) spaces them proportionally. Index = code point for ASCII and
Latin-1; the unused C1 range 0x80-0x9F holds 32 letters of Latin Extended-A.

usage: bdf2font.py <font.bdf> <name> <out.c>
"""
import sys

EXTRA = "ŒœŠšŽžŸŁłŐőŰűČčĚěŘřŃńŚśŹźŻżĄąĘęĆć"


def parse(path):
    glyphs, ascent, cur = {}, None, None
    with open(path, encoding="latin-1") as f:
        lines = iter(f.read().splitlines())
    for line in lines:
        parts = line.split()
        if not parts:
            continue
        if parts[0] == "FONT_ASCENT":
            ascent = int(parts[1])
        elif parts[0] == "STARTCHAR":
            cur = {}
        elif parts[0] == "ENCODING":
            cur["code"] = int(parts[1])
        elif parts[0] == "BBX":
            cur["bbx"] = [int(p) for p in parts[1:5]]
        elif parts[0] == "BITMAP":
            rows = []
            for row in lines:
                if row.startswith("ENDCHAR"):
                    break
                rows.append(int(row, 16) >> (4 * len(row) - 8))   # the leftmost 8 pixels, MSB first
            cur["rows"] = rows
            glyphs[cur["code"]] = cur
    return glyphs, ascent


def cell(g, ascent):
    """The glyph in an 8x8 cell, as rows of bit 0 = left pixel, moved to the left edge."""
    w, h, xoff, yoff = g["bbx"]
    top = ascent - (yoff + h)
    out = [0] * 8
    for r, bits in enumerate(g["rows"]):
        y = top + r
        if not 0 <= y < 8:
            continue
        for x in range(w):
            if bits & (0x80 >> x) and 0 <= xoff + x < 8:
                out[y] |= 1 << (xoff + x)
    lit = 0
    for v in out:
        lit |= v
    shift = (lit & -lit).bit_length() - 1 if lit else 0
    return [v >> shift for v in out]


def main():
    if len(sys.argv) != 4:
        sys.exit(__doc__)
    glyphs, ascent = parse(sys.argv[1])
    codes = [0] * 256
    for i in range(0x20, 0x7F):
        codes[i] = i
    for i in range(0xA0, 0x100):
        codes[i] = i
    for i, ch in enumerate(EXTRA):
        codes[0x80 + i] = ord(ch)
    table, points = [], []
    for i, c in enumerate(codes):
        g = glyphs.get(c) if c else None
        if c and g is None:
            print(f"no glyph for U+{c:04X}, left out", file=sys.stderr)
            c = 0
        table.append(cell(g, ascent) if g else [0] * 8)
        points.append(c)
    name = sys.argv[2]
    with open(sys.argv[3], "w", newline="\n") as f:
        f.write("/* Generated by display/tools/bdf2font.py from the X11 misc-fixed font\n")
        f.write(" * (\"Public domain font.  Share and enjoy.\"); do not edit. */\n")
        f.write('#include "dsd.h"\n\n')
        f.write(f"static const uint8_t glyphs[256 * 8] = {{\n")
        for i, rows in enumerate(table):
            f.write("  " + ", ".join(f"0x{v:02x}" for v in rows) + f",  /* {i:#04x} */\n")
        f.write("};\n\n")
        f.write("static const uint16_t codepoints[256] = {\n")
        for i in range(0, 256, 8):
            f.write("  " + ", ".join(f"0x{v:04x}" for v in points[i:i + 8]) + ",\n")
        f.write("};\n\n")
        f.write(f"const dsd_font_t {name} = {{ glyphs, codepoints }};\n")


main()
